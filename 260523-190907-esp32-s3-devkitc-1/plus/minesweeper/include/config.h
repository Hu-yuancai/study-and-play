/*
 * config.h — 硬件引脚配置 + 全局常量定义
 * ============================================================================
 * 【这个文件的作用】
 * 把所有硬件引脚的定义集中在一个地方。当你需要改接线时，只需要改这个文件，
 * 不用去每个源代码文件里翻找引脚号。这是嵌入式开发的"最佳实践"。
 *
 * 【新手教程：什么是引脚(Pin)？】
 * 开发板上的金属针脚就是"引脚"，每个引脚有一个编号（如 GPIO1, GPIO2...）。
 * 你可以用程序控制引脚输出高电压(3.3V)或低电压(0V)，也可以读取引脚上的电压。
 * 这就像开发板的手和眼睛——输出=控制外设，输入=感知外界。
 *
 * 【ESP32-S3-DevKitC-1 引脚布局提示】
 * 开发板上印有引脚编号，如图中 D1, D2...，它们对应 ESP32 的 GPIO 编号。
 * 选引脚时要注意：
 *   - 有些引脚在启动时有特殊功能（如 GPIO0 用于进入下载模式）
 *   - 有些引脚用于内部 Flash/PSRAM，不能用
 *   - ADC2 引脚在 Wi-Fi 开启时不可用
 *   建议优先使用 GPIO1-21 中不与其他功能冲突的引脚
 */

#ifndef CONFIG_H       // 头文件保护：防止同一个文件被重复包含
#define CONFIG_H       // 如果没定义过 CONFIG_H，就定义它
                       // 编译器第二次遇到 #include "config.h" 时会跳过整个文件

#include <Arduino.h>   // Arduino 核心库，提供 pinMode, digitalWrite 等基础函数

// ============================================================================
// 第一部分：ILI9341 TFT LCD 引脚配置 (SPI 通信，14 脚模块，带 SD 卡槽)
// ============================================================================
//
// 【通信协议简介：SPI (Serial Peripheral Interface)】
// SPI 是一种高速的串行通信协议，需要 4 根线：
//   SCK  (Serial Clock)     — 时钟线，同步数据传输节奏
//   MOSI (Master Out Slave In) — 主设备发送、从设备接收
//   MISO (Master In Slave Out) — 从设备发送、主设备接收
//   CS   (Chip Select)      — 片选线，选中哪个设备（可接多个设备共享 SPI 总线）
// 另外还有：
//   DC   (Data/Command)     — 告诉屏幕"我发的是命令还是图像数据"
//   RST  (Reset)            — 硬件复位引脚
//
// 【ILI9341 模块引脚对应关系】
// 模块丝印 → ESP32 引脚 → 功能说明
// VCC      → 3.3V       → 电源正极（注意：大多数模块是 3.3V，不能用 5V！）
// GND      → GND        → 电源负极 / 接地
// CS       → GPIO10     → 片选：低电平时屏幕"听"SPI 总线
// RESET    → GPIO8      → 复位：拉低再拉高可以重启屏幕
// DC/RS    → GPIO4      → 数据/命令选择：HIGH=发图像数据, LOW=发配置命令
// SDI(MOSI)→ GPIO11     → 数据输入（主机→屏幕）
// SCK      → GPIO12     → 时钟信号
// LED      → 3.3V       → 背光控制（接 3.3V=常亮，接 GPIO 可调亮度）
// SDO(MISO)→ GPIO13     → 数据输出（屏幕→主机，读取屏幕状态用，很少用到）
//
#define LCD_CS_PIN    10   // 片选引脚 (Chip Select)
#define LCD_DC_PIN    4    // 数据/命令选择引脚 (Data/Command)
#define LCD_RST_PIN   8    // 复位引脚 (Reset)
#define LCD_MOSI_PIN  11   // 主机输出从机输入 (Master Out Slave In)
#define LCD_MISO_PIN  13   // 主机输入从机输出 (Master In Slave Out)
#define LCD_SCLK_PIN  12   // 串行时钟 (Serial Clock)

// ============================================================================
// 第二部分：OLED SSD1306 引脚配置 (I2C 通信)
// ============================================================================
//
// 【通信协议简介：I2C (Inter-Integrated Circuit)】
// I2C 是一种两线制的串行通信协议：
//   SDA (Serial Data)  — 数据线，传输所有数据
//   SCL (Serial Clock) — 时钟线，同步节奏
// 优点：只需要 2 根线就能接很多设备（每个设备有唯一地址）
// 缺点：速度比 SPI 慢
//
// 【SSD1306 OLED 模块】
// 128x64 像素的单色 OLED 屏幕，通常有 4 个引脚：
//   VCC → 3.3V
//   GND → GND
//   SCL → 时钟
//   SDA → 数据
//
#define OLED_SDA_PIN  6    // I2C 数据线
#define OLED_SCL_PIN  7    // I2C 时钟线
#define OLED_ADDR     0x3C // I2C 设备地址（SSD1306 默认 0x3C，有些模块是 0x3D）
                           // 如果屏幕不显示，试试改成 0x3D

// ============================================================================
// 第三部分：4x4 矩阵键盘引脚配置
// ============================================================================
//
// 【什么是矩阵键盘？】
// 4x4 = 4行×4列 = 16 个按键，但只需要 8 个 GPIO 引脚。
// 原理：按下一个键时，它会把某一行和某一列连接起来。
// 程序轮流把每一行拉低，然后读每一列——如果某列读到低电平，
// 说明这一行和这一列的交叉点上的按键被按下了。
//
// 【接线说明】
// 键盘通常有 8 个引脚：R1-R4 (行) + C1-C4 (列)
// 用杜邦线连接到 ESP32 对应的 GPIO
//
#define KB_ROW1  1    // 第 1 行 → GPIO1
#define KB_ROW2  2    // 第 2 行 → GPIO2
#define KB_ROW3  3    // 第 3 行 → GPIO3
#define KB_ROW4  5    // 第 4 行 → GPIO5 (跳过 GPIO4 因为它用于 LCD_DC)
#define KB_COL1  14   // 第 1 列 → GPIO14
#define KB_COL2  15   // 第 2 列 → GPIO15
#define KB_COL3  16   // 第 3 列 → GPIO16
#define KB_COL4  17   // 第 4 列 → GPIO17

// ============================================================================
// 第四部分：无源蜂鸣器配置 (PWM 音频输出)
// ============================================================================
//
// 【无源蜂鸣器 vs 有源蜂鸣器】
// - 有源蜂鸣器：内部有振荡电路，通电就响，只能发出固定频率的声音
// - 无源蜂鸣器：只是一个压电陶瓷片，需要 PWM 信号才能发声
//               优点：可以发出不同频率的声音（播放音乐！）
//               缺点：需要程序生成波形
//
// 【三脚蜂鸣器模块引脚】
// VCC → 3.3V (电源)
// GND → GND  (接地)
// I/O → GPIO (信号输入)
//
// 【工作原理】
// 此模块是"低电平触发"：VCC 接电源，I/O 通过蜂鸣器内部接到 VCC。
// 当 I/O 为高电平(3.3V)时，蜂鸣器两端等电位 → 不导通 → 不响。
// 当 I/O 为低电平(0V)时，电流从 VCC 经蜂鸣器流向 I/O → 导通 → 发声。
// PWM 快速切换高低电平，就能控制音调和音量。
//
#define AUDIO_PIN     18   // 蜂鸣器信号引脚
#define AUDIO_CHANNEL 0    // LEDC PWM 通道号 (ESP32-S3 有 8 个通道 0-7)
                           // 每个通道可以独立输出不同频率的 PWM

// ============================================================================
// 第五部分：按键键值定义（与 keyboard.cpp 的 keyMap 对应）
// ============================================================================
//
// 【为什么用宏定义而不是直接用数字？】
// 代码中写 `if (key == KEY_UP)` 比 `if (key == 1)` 更容易理解。
// 如果将来需要改键值映射，只需要改这里，不需要改所有使用的地方。
//
#define KEY_NONE   0    // 没有按键按下
#define KEY_UP     1    // 方向键 ↑
#define KEY_DOWN   2    // 方向键 ↓
#define KEY_LEFT   3    // 方向键 ←
#define KEY_RIGHT  4    // 方向键 →
#define KEY_ENTER  5    // 确认键
#define KEY_BACK   6    // 返回键
#define KEY_FIRE   7    // 发射键（飞机游戏用）
#define KEY_1      8    // 数字键 1（钢琴游戏轨道1）
#define KEY_2      9    // 数字键 2（钢琴游戏轨道2）
#define KEY_3      10   // 数字键 3（钢琴游戏轨道3）
#define KEY_4      11   // 数字键 4（钢琴游戏轨道4）
#define KEY_5      12   // 数字键 5（切换曲目/光标上移）
#define KEY_6      13   // 数字键 6（切换曲目/光标下移）
#define KEY_7      14   // 数字键 7
#define KEY_8      15   // 数字键 8
#define KEY_9      16   // 数字键 9 (仅 Ghost Shell 使用)

// ============================================================================
// 第六部分：屏幕尺寸参数
// ============================================================================
//
// 【ILI9341 LCD】
// 物理分辨率: 240×320 像素（竖屏模式）
// 注意：如果 rotation 设为横屏，宽高会对调
//
// 【SSD1306 OLED】
// 物理分辨率: 128×64 像素
//
#define LCD_WIDTH   240    // LCD 屏幕宽度（像素）
#define LCD_HEIGHT  320    // LCD 屏幕高度（像素）
#define OLED_WIDTH  128    // OLED 屏幕宽度（像素）
#define OLED_HEIGHT 64     // OLED 屏幕高度（像素）

// ============================================================================
// 第七部分：帧率控制
// ============================================================================
//
// 【什么是帧率(Frame Rate)？】
// 每秒刷新屏幕的次数。60 FPS = 每秒画 60 次 = 每帧约 16.67 毫秒。
// 人眼在 30 FPS 以上就会觉得流畅，60 FPS 是非常流畅的体验。
// 更高的帧率消耗更多 CPU，但视觉改善不明显。
//
#define FRAME_RATE  60     // 目标帧率（每秒帧数）
#define FRAME_MS    (1000 / FRAME_RATE)  // 每帧的毫秒数 = 1000/60 ≈ 16ms
                                          // 宏展开后约等于 16

#endif  // CONFIG_H 结束
