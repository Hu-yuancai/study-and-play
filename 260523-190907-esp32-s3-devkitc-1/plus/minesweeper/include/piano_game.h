/*
 * piano_game.h — 钢琴块节奏游戏模块（头文件）
 * ============================================================================
 * 【游戏简介】
 * 类似"别踩白块"的节奏游戏。音符从屏幕上方落下，到判定线时按对应按键。
 * 4 条轨道，6 首内置曲目，支持短按和长按两种音符类型。
 * OLED 副屏显示角色表情动画，响应按键和 Combo。
 *
 * 【操作方式】
 * 1/2/3/4 或 4个方向键：按对应轨道（1=轨道0=左, 4=轨道3=右）
 * 5/6：切换曲目
 * 确认键：暂停/继续
 * 返回键：退出到主菜单
 */

#ifndef PIANO_GAME_H
#define PIANO_GAME_H

#include <Arduino.h>

// ============================================================================
// 公共接口
// ============================================================================

/*
 * pianoGameInit() — 初始化钢琴游戏
 * 重置分数、combo，加载当前曲目
 * 在进入游戏时调用一次
 */
void pianoGameInit();

/*
 * pianoGameLoop(key) — 每帧调用，处理游戏逻辑
 * @param key  当前按下的键值（KEY_NONE 表示没有按键）
 */
void pianoGameLoop(uint8_t key);

/*
 * pianoGameNextSong() — 切换到下一首曲目
 * 重置游戏状态并加载新曲目
 */
void pianoGameNextSong();

/*
 * pianoGamePrevSong() — 切换到上一首曲目
 * 重置游戏状态并加载新曲目
 */
void pianoGamePrevSong();

#endif  // PIANO_GAME_H 结束
