/*
 * oledShowFace(faceType) - 以颜文字(kaomoji)显示表情
 * 在 OLED 上居中绘制对应颜文字字符串 + 边框文字
 * 颜文字约 5-8 字符宽 (~60-96px), 居中于 128px 宽屏幕
 * @param faceType  表情索引 0-13
 */
void oledShowFace(uint8_t faceType) {
  if (faceType >= FACE_COUNT) return;  // 越界保护

  oledClear();

  // 顶部文字
  if (borderTop[0]) {
    oledDrawString(40, 0, borderTop);
  }

  // 底部文字
  if (borderBottom[0]) {
    oledDrawString(40, 52, borderBottom);
  }

  // 获取颜文字字符串
  const char* kao = faceKaomoji[faceType];

  // 计算字符串像素宽度, 居中绘制
  // 12px 中文字体下每个字符约 12px 宽 (西文约 6px)
  // 粗略估算: strlen 数中文字符 + ASCII字符宽度
  int w = u8g2_oled.getStrWidth(kao);
  int x = (128 - w) / 2;   // 水平居中
  if (x < 0) x = 0;

  // 在 OLED 中央 (y≈28) 以大字绘制颜文字
  oledDrawString(x, 28, kao);

  oledRefresh();
}

/*
 * showFullImage(src) - 显示 128×64 全屏 XBM 图像
 *
 * 【核心算法】
 * XBM 数据是"行优先"排列的: 64行 × 每行16字节(128位)
 * U8g2 缓冲是"页优先"排列的: 8页 × 每页128字节
 *
 * 需要做坐标变换:
 *   XBM[row][col_byte].bit[7-(col%8)] → U8g2[page][col].bit[row%8]
 *
 * 详细步骤:
 *   遍历每一页(page 0-7)
 *     遍历每一列(col 0-127)
 *       从 XBM 对应位置取出 8 个垂直像素
 *       合并成 1 字节写入 U8g2 缓冲
 *
 * 颜色反转 ^ 0xFF: 因为 XBM 中 1=黑而 OLED 中 1=亮
 *
 * 带缓存机制: 静态变量保存上一次的源指针,
 * 如果连续显示同一张图就跳过转换(节省大量 CPU 时间)
 *
 * @param src  指向 Flash 中 1024 字节 XBM 数据的指针
 */
void showFullImage(const uint8_t* src) {
  static uint8_t buf[1024];            // 转换后的 U8g2 格式缓冲
  static const uint8_t* cachedSrc = NULL; // 上次转换的源地址

  // 缓存检查: 如果这次要显示的图和上次一样，直接复用缓冲
  if (cachedSrc != src) {
    // 遍历 8 页
    for (int page = 0; page < 8; page++) {
      // 遍历 128 列
      for (int col = 0; col < 128; col++) {
        uint8_t v = 0;  // 这一列 8 个垂直像素的值

        // 遍历该列 8 个垂直像素 (bit 0-7)
        for (int b = 0; b < 8; b++) {
          int py = page * 8 + b;         // 对应的 Y 坐标 (0-63)
          int srcByte = py * 16 + (col >> 3); // XBM 中的字节索引
          int srcBit  = 7 - (col & 7);        // XBM 字节中的位位置
          // 如果 XBM 中该像素为 1
          if (pgm_read_byte(&src[srcByte]) & (1 << srcBit))
            v |= (1 << b);  // 设置 U8g2 缓冲的对应位
        }
        buf[col + page * 128] = v ^ 0xFF; // 存入缓冲 + 颜色反转
      }
    }
    cachedSrc = src;  // 更新缓存标记
  }

  // 将 1024 字节缓冲复制到 U8g2 的内部缓冲
  memcpy(u8g2_oled.getBufferPtr(), buf, 1024);
  u8g2_oled.sendBuffer();  // 发送到 OLED
}

