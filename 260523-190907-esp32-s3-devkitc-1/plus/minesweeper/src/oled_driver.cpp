/*
 * oledShowBlinkingFace(faceA, faceB, interval) - 眨眼动画
 * 利用 millis() 时间戳在两个表情间循环切换
 *
 * 工作原理:
 *   (millis() / interval) % 2
 *   这个表达式在 interval 毫秒内保持不变，然后翻转
 *   比如 interval=500: 0-499ms→0, 500-999ms→1, 1000-1499ms→0...
 *
 * @param faceA    表情 A (通常睁眼)
 * @param faceB    表情 B (通常闭眼)
 * @param interval 切换间隔(毫秒), 值越小眨眼越快
 */
void oledShowBlinkingFace(uint8_t faceA, uint8_t faceB, uint32_t interval) {
  bool showA = (millis() / interval) % 2 == 0;
  oledShowFace(showA ? faceA : faceB);
}

