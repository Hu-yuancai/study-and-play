/*
 * initOLED() - 初始化 OLED 模块 (I2C + U8g2)
 * 1) 启动I2C总线 (SDA=6, SCL=7)
 * 2) 初始化U8g2库
 * 3) 启用UTF-8编码(支持中文)并设置中文字体
 * 4) 清空显示
 */
void initOLED() {
  Wire.begin(OLED_SDA_PIN, OLED_SCL_PIN);      // 启动 I2C
  u8g2_oled.begin();                            // 初始化 SSD1306
  u8g2_oled.enableUTF8Print();                  // 启用 UTF-8 打印(中文支持)
  u8g2_oled.setFont(u8g2_font_wqy12_t_gb2312); // 中文字体: wqy(文泉驿) 12px
  u8g2_oled.clearBuffer();                      // 清空内部缓冲
  u8g2_oled.sendBuffer();                       // 刷新显示
}

void oledClear()            { u8g2_oled.clearBuffer(); }
void oledRefresh()          { u8g2_oled.sendBuffer(); }

// 画 UTF-8 文本, y+12 是 U8g2 的基线偏移习惯
void oledDrawString(int x, int y, const char* str) {
  u8g2_oled.drawUTF8(x, y + 12, str);
}

